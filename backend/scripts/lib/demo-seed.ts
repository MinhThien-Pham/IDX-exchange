export async function seedDemo(db: Database) {
  const rows: ListingInsert[] = homes.map((home, index) => ({
    source: 'demo',
    externalId: home[0],
    address: home[1],
    city: home[2],
    state: home[3],
    zipcode: home[4],
    price: home[5],
    bedrooms: home[6],
    bathrooms: home[7],
    squareFeet: home[8],
    latitude: home[9],
    longitude: home[10],
    listedAt: `2026-10-${String(1 + index).padStart(2, '0')}`,
    photos: [images[index % images.length]!, images[(index + 1) % images.length]!],
    description: `Synthetic portfolio demo listing in ${home[2]}. An inviting layout with bright living spaces. The address, price, and property details are invented for learning and testing.`,
    propertyType: 'Residential',
    propertySubType: home[6] <= 2 ? 'Condominium' : 'Single Family Residence',
    yearBuilt: 1990 + index,
    lotSizeAcres: '0.1500',
    parkingSpaces: home[6] <= 2 ? 1 : 2,
    rawData: { synthetic: true },
  }));
  const saved = await upsertListings(db, rows);
  const listingIds = new Map(saved.map((row) => [row.externalId, row.id]));
  const today = new Date();
  today.setUTCDate(today.getUTCDate() + 7);
  const date = today.toISOString().slice(0, 10);
  await upsertOpenHouses(
    db,
    ['DEMO-001', 'DEMO-003', 'DEMO-008'].map((externalId, index) => ({
      source: 'demo',
      externalId: `${externalId}-OH-1`,
      listingId: listingIds.get(externalId)!,
      date,
      startTime: '13:00:00',
      endTime: '16:00:00',
      timeZone: index === 2 ? 'America/New_York' : 'America/Los_Angeles',
      remarks: 'Synthetic open house for the portfolio demo. No real event takes place.',
      rawData: { synthetic: true },
    })),
  );
  return { listings: rows.length, openHouses: 3 };
}
